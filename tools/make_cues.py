"""Find the start time of each cue phrase in the word-level transcript (in order) and emit src/cues.ts."""
import json, re, sys

words = json.load(open(sys.argv[1]))
cues = [l.split('|', 1) for l in open(sys.argv[2]).read().splitlines() if '|' in l and not l.startswith('#')]
norm = lambda s: re.sub(r"[^a-z0-9]", "", s.lower())
W = [norm(w['w']) for w in words]

pos, out, bad = 0, [], []
for key, phrase in cues:
    toks = [norm(t) for t in phrase.split() if norm(t)]
    found = None
    for i in range(pos, len(W) - len(toks) + 1):
        if all(W[i + j].startswith(t) or t.startswith(W[i + j]) and W[i + j] for j, t in enumerate(toks)):
            found = i; break
    if found is None:
        bad.append((key, phrase)); continue
    out.append((key.strip(), words[found]['s'], words[found + len(toks) - 1]['e']))
    pos = found + 1

with open(sys.argv[3], 'w') as fh:
    fh.write('// Generated by tools/make_cues.py — start/end (seconds) of spoken cue phrases.\n')
    fh.write('export const Q = {\n')
    for k, s, e in out:
        fh.write(f'  {k}: {s},\n')
    fh.write('} as const;\n\nexport const QE = {\n')
    for k, s, e in out:
        fh.write(f'  {k}: {e},\n')
    fh.write(f'}} as const;\n\nexport const AUDIO_END = {words[-1]["e"]};\n')
for b in bad: print('NOT FOUND:', b)
print(len(out), 'cues')

# manual cues Whisper missed (from silence analysis) + JSON copy for the music generator
extra = {'autoavio': 365.8}
with open(sys.argv[3], 'a') as fh:
    fh.write('\nexport const QX = ' + json.dumps(extra) + ' as const;\n')
json.dump({k: s for k, s, e in out} | extra | {'_end': words[-1]['e']}, open(sys.argv[3].replace('.ts', '.json'), 'w'), indent=1)
